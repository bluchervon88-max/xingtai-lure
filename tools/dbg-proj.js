const D2R=Math.PI/180;
const density=3.75;
const screenW=Math.round(384*density);
const plotW=(screenW-12*density)-16*density;
const plotH=(1640-32*density)-12*density;
const dMinLat=36.85,dMaxLat=37.60,dMinLon=113.85,dMaxLon=115.70;
const bMinLon=113.061,bMaxLon=116.280;
const centerLat=(dMinLat+dMaxLat)/2;
const cosLat=Math.cos(centerLat*D2R);
const span=bMaxLon-bMinLon;

const pxPerLat = plotW / (span*cosLat);
const base = pxPerLat/100;
const pxPerLat2 = base*100;
const pxPerLon = pxPerLat2*cosLat;
const visLon = plotW/pxPerLon;
const visLat = plotH/pxPerLat2;

console.log('  density        = '+density);
console.log('  screenW        = '+screenW);
console.log('  plotW          = '+plotW+'   plotH = '+plotH);
console.log('  centerLat      = '+centerLat.toFixed(4)+'   cosLat = '+cosLat.toFixed(6));
console.log('  span(经度)     = '+span.toFixed(4)+'°');
console.log('');
console.log('  pxPerLat(每度) = plotW/(span*cosLat) = '+plotW+'/('+span.toFixed(3)+'*'+cosLat.toFixed(4)+') = '+pxPerLat.toFixed(2));
console.log('  base(每0.01°)  = '+base.toFixed(4));
console.log('  pxPerLat 回算  = '+pxPerLat2.toFixed(2)+'   (应等于上面的值)');
console.log('  pxPerLon(每度) = '+pxPerLon.toFixed(2));
console.log('');
console.log('  visLon(1x)     = plotW/pxPerLon = '+plotW+'/'+pxPerLon.toFixed(2)+' = '+visLon.toFixed(4)+'°');
console.log('  span           = '+span.toFixed(4)+'°');
console.log('  比值           = '+(visLon/span).toFixed(4)+'   <-- 应为 1.0000');
console.log('');
console.log('  visLat(1x)     = plotH/pxPerLat = '+visLat.toFixed(4)+'°');
console.log('  可见南北       = '+(visLat*111.32).toFixed(1)+' km');
console.log('  可见东西       = '+(visLon*111.32*cosLat).toFixed(1)+' km');
console.log('');
console.log('  【2x】');
console.log('  visLon = '+(visLon/2).toFixed(4)+'° = '+(visLon/2*111.32*cosLat).toFixed(1)+' km');
console.log('  钓点经度跨度 1.850° = '+(1.850*111.32*cosLat).toFixed(1)+' km');
console.log('  余量 = '+((visLon/2)/1.850).toFixed(3));